import { EmbedBuilder } from 'discord.js';
import { MarketOverview } from '../services/marketData';

export function createFlowForgeEmbed(data: MarketOverview) {
  const isBull = data.prediction.direction === 'BULLISH';
  const color = 0x8B5CF6; // Cyber Violet

  return new EmbedBuilder()
    .setTitle(`⚡ VIXY AI • FLOW-FORGE INSTITUTIONAL DEPTH`)
    .setColor(color)
    .setDescription(`*Institutional Order Blocks, Liquidity Sweeps & Taker Absorption Analysis*`)
    .addFields(
      { name: '📦 Order Blocks', value: `\`$${(data.price * 0.998).toFixed(2)} - $${(data.price * 0.999).toFixed(2)}\` (Institutional Support)`, inline: false },
      { name: '🧹 Liquidity Sweeps', value: `\`+$12.4M Short Liquidations\` swept at high of range`, inline: true },
      { name: '🧽 Absorption Rate', value: `\`94.2%\` Sell orders absorbed by limit buyers`, inline: true },
      { name: '📊 Orderbook Imbalance', value: `\`+1,820 BTC\` Taker Buy Delta in 15m window`, inline: true },
      { name: '🧠 Institutional AI Explanation', value: data.prediction.reasoning, inline: false }
    )
    .setFooter({ text: 'VIXY AI Core • Confidential Flow-Forge Deep Inspection' })
    .setTimestamp();
}

